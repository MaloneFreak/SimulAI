#!/usr/bin/env node
/**
 * Builds dist/SimulAI-standalone.html: ONE self-contained HTML file that works
 * offline (no CDN, no extra files). Used to create the release asset.
 *
 * What gets inlined into SimulAI.html:
 *   - src/script.js and src/languages.js
 *   - Tailwind CSS, compiled and minified (replaces the cdn.tailwindcss.com runtime)
 *   - MathJax 3 (SVG output, so no external web fonts are needed)
 *   - Inter and JetBrains Mono (Latin subset, as base64 woff2)
 *
 * Usage (from the repository root):
 *   cd tools && npm install && npm run build
 */
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const nm = (...parts) => join(here, 'node_modules', ...parts);
const read = (...parts) => readFileSync(join(root, ...parts), 'utf8');

// Replace exactly what we expect to find. Fail loudly if SimulAI.html changed shape.
function swap(html, pattern, replacement, label) {
  const next = html.replace(pattern, () => replacement);
  if (next === html) {
    throw new Error(`Could not find ${label} in SimulAI.html. If the HTML changed, update tools/build-standalone.mjs.`);
  }
  return next;
}

// Safe to place inside an inline <script>.
// "</script" would end the tag early, and "<!--" followed by "<script" confuses the HTML parser.
// Escaping as "<\/script" and "<\!--" keeps the same meaning inside JS strings and regex literals.
function inlineJs(js, label) {
  if (/<script/i.test(js)) throw new Error(`${label} contains "<script", which is unsafe to inline.`);
  return js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
}

// 1) Tailwind: compile only the classes used in the HTML and in src/*.js
const tmp = mkdtempSync(join(tmpdir(), 'simulai-'));
const cssFile = join(tmp, 'tailwind.css');
execFileSync(
  process.execPath,
  [nm('tailwindcss', 'lib', 'cli.js'), '--content', 'SimulAI.html,src/*.js', '--minify', '-o', cssFile],
  { cwd: root, stdio: 'pipe' },
);
const tailwindCss = readFileSync(cssFile, 'utf8');
rmSync(tmp, { recursive: true, force: true });

// 2) Fonts as base64 @font-face
const fontFace = (family, weight, file) => {
  const b64 = readFileSync(file).toString('base64');
  return `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:swap;src:url(data:font/woff2;base64,${b64}) format('woff2');}`;
};
const fonts = [
  ...[400, 500, 600, 700].map((w) =>
    fontFace('Inter', w, nm('@fontsource', 'inter', 'files', `inter-latin-${w}-normal.woff2`))),
  fontFace('JetBrains Mono', 400, nm('@fontsource', 'jetbrains-mono', 'files', 'jetbrains-mono-latin-400-normal.woff2')),
].join('\n');

// 3) MathJax (SVG build: self-contained, no font files to fetch)
const mathjax = inlineJs(readFileSync(nm('mathjax', 'es5', 'tex-svg.js'), 'utf8'), 'MathJax');

// 4) App code
const scriptJs = inlineJs(read('src', 'script.js'), 'src/script.js');
const languagesJs = inlineJs(read('src', 'languages.js'), 'src/languages.js');

// 5) Assemble
let html = read('SimulAI.html');
html = swap(html, /<!DOCTYPE html>/i, '<!DOCTYPE html>\n<!-- Generated by tools/build-standalone.mjs from SimulAI.html + src/. Do not edit by hand. -->', 'doctype');
html = swap(html, /<script src="https:\/\/cdn\.tailwindcss\.com"><\/script>\s*/, '', 'Tailwind CDN script');
html = swap(html, /<script src="\.\/src\/script\.js" defer><\/script>\s*/, '', 'script.js tag');
html = swap(html, /<script src="\.\/src\/languages\.js" defer><\/script>\s*/, '', 'languages.js tag');
html = swap(html, /<link rel="preconnect"[^>]*>\s*/, '', 'Google Fonts preconnect');
html = swap(html, /<link href="https:\/\/fonts\.googleapis\.com[^>]*>\s*/, '', 'Google Fonts stylesheet');
html = swap(html, /<script id="mathjax-script"[^>]*><\/script>/, `<script id="mathjax-script">${mathjax}</script>`, 'MathJax script');
// Tailwind's preflight sets `svg { display: block }`. MathJax's SVG output draws each equation as an <svg>,
// so inline math would break onto its own line and display math would lose its centering.
// (The CDN version used MathJax's CHTML output, which has no <svg>, so it never hit this.)
const mathjaxFix = 'mjx-container svg{display:inline}';
// Tailwind first, then the page's own <style>, same cascade order as the CDN version.
html = swap(html, '<style>', `<style id="vendor">\n${fonts}\n${tailwindCss}\n${mathjaxFix}\n</style>\n    <style>`, 'page <style>');
// App scripts at the end of <body>, same order as before (script.js, then languages.js).
html = swap(html, '</body>', `<script>${scriptJs}</script>\n<script>${languagesJs}</script>\n</body>`, '</body>');

// 6) Self-check: the page structure must not load anything from the network.
// Only the markup and the CSS are inspected: the inlined JS libraries legitimately contain
// URL strings (for example the link in MathJax's "About" dialog), which are not resource loads.
const markup = html.replace(/<(script|style)\b[^>]*>[\s\S]*?<\/\1>/gi, '');
const css = [...html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)].map((m) => m[1]).join('\n');
const problems = [
  ...(markup.match(/<[^>]+\s(?:src|href)\s*=\s*["']?(?:https?:)?\/\/[^>]*>/gi) ?? []),
  ...(html.match(/<script\b[^>]*\ssrc\s*=/gi) ?? []),
  ...(html.match(/<link\b[^>]*>/gi) ?? []),
  ...(css.match(/url\(\s*["']?(?!data:)[^)]*\)/gi) ?? []),
  ...(css.match(/@import[^;]*;/gi) ?? []),
];
if (problems.length) {
  throw new Error(`Self-check failed: external resources still referenced:\n  ${problems.join('\n  ')}`);
}

mkdirSync(join(root, 'dist'), { recursive: true });
const out = join(root, 'dist', 'SimulAI-standalone.html');
writeFileSync(out, html);
console.log(`OK  ${out}  (${(Buffer.byteLength(html) / 1024 / 1024).toFixed(2)} MB)`);
